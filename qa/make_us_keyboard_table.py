"""Generate probe/us_keyboard_table.inc from the Windows US layout (00000409) on this PC.

The game names keys at startup with MapVirtualKeyExW(scan, 3, layout) and ToUnicodeEx with an all-zero key state.
The probe answers those two calls from this table when no US layout is loaded on the player's PC, so every PC
gets the same internal key names without loading or changing any Windows keyboard layout.
Usage (needs the US layout among the loaded layouts): python -I qa/make_us_keyboard_table.py
"""
import ctypes
from pathlib import Path

ROOT = Path(__file__).absolute().parents[1]
user32 = ctypes.WinDLL("user32")
user32.GetKeyboardLayoutList.argtypes = [ctypes.c_int, ctypes.POINTER(ctypes.c_void_p)]
user32.MapVirtualKeyExW.argtypes = [ctypes.c_uint, ctypes.c_uint, ctypes.c_void_p]
user32.MapVirtualKeyExW.restype = ctypes.c_uint
user32.ToUnicodeEx.argtypes = [ctypes.c_uint, ctypes.c_uint, ctypes.c_char_p, ctypes.c_wchar_p, ctypes.c_int, ctypes.c_uint, ctypes.c_void_p]


def main():
    count = user32.GetKeyboardLayoutList(0, None)
    layouts = (ctypes.c_void_p * count)()
    user32.GetKeyboardLayoutList(count, layouts)
    us = next((h for h in layouts if (h or 0) & 0xFFFFFFFF == 0x04090409), None)
    if not us:
        raise SystemExit("The standard US layout (04090409) must be loaded to generate the table")
    state = bytes(256)
    rows = []
    for scan in list(range(1, 0x80)) + [0xE000 | s for s in range(1, 0x80)]:
        vk = user32.MapVirtualKeyExW(scan, 3, us)
        if not vk:
            continue
        out = ctypes.create_unicode_buffer(4)
        got = user32.ToUnicodeEx(vk, scan & 0xFF, state, out, 4, 0, us)
        ch = ord(out[0]) if got == 1 else 0
        rows.append((scan, vk, ch))
    lines = ["// Generated by qa/make_us_keyboard_table.py from the Windows US layout 00000409: {scan, vk, unshifted char}.",
             "// Used only when no US layout is loaded on the player's PC (see canonicalKeyboardLayout in probe.cpp)."]
    lines += ["{0x%04x,0x%02x,0x%04x}," % row for row in rows]
    (ROOT / "probe" / "us_keyboard_table.inc").write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print("US_KEYBOARD_TABLE rows=%d printable=%d" % (len(rows), sum(1 for r in rows if r[2])))


if __name__ == "__main__":
    main()
