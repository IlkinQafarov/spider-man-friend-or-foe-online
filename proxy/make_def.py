#!/usr/bin/env python
"""Generate d3d9_forwards.h (linker forwarder pragmas) from a real d3d9.dll's export table.

Every named export of the system d3d9 is forwarded to d3d9_chain.<name>, so the
proxy is a complete, drop-in d3d9 that passes everything through to a machine-local
copy of the real library. Run on the machine that will run the game, against that
machine's 32-bit d3d9 (C:\\Windows\\SysWOW64\\d3d9.dll), because the export set can
differ slightly between Windows versions.

Usage:
    python -I make_def.py --d3d9 C:\\Windows\\SysWOW64\\d3d9.dll --out d3d9_forwards.h
    python -I make_def.py --d3d9 ... --out d3d9_forwards.h --chain-copy <dir>

--chain-copy also copies the source d3d9.dll into <dir> as d3d9_chain.dll (the
target of the forwarders). The copy is the user's own system file and is never
redistributed by this tool.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

# dumpbin /exports rows look like: "   37    A 000816B0 Direct3DCreate9".
# Columns: ordinal(dec) hint(hex) RVA(hex) name. NONAME / ordinal-only rows have no
# trailing identifier and are skipped (a name-importing game never needs them).
ROW = re.compile(r"^\s*(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+([A-Za-z_][A-Za-z0-9_]*)\s*$")


def find_dumpbin():
    for name in ("dumpbin", "dumpbin.exe"):
        path = shutil.which(name)
        if path:
            return path
    sys.exit("dumpbin not found on PATH. Run this from a Visual Studio command "
             "prompt (vcvars32), the same shell used to build the proxy.")


def exports(dumpbin, dll):
    out = subprocess.run([dumpbin, "/exports", dll],
                         capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("dumpbin failed:\n" + out.stdout + out.stderr)
    found = []
    seen = set()
    for line in out.stdout.splitlines():
        if "forwarded to" in line:
            # A system d3d9 export that is itself a forwarder: forward by name only.
            m = re.search(r"\s([A-Za-z_][A-Za-z0-9_]*)\s+\(forwarded", line)
            if m and m.group(1) not in seen:
                seen.add(m.group(1))
                found.append((None, m.group(1)))
            continue
        m = ROW.match(line)
        if m:
            name = m.group(2)
            if name in seen:
                continue
            seen.add(name)
            found.append((int(m.group(1)), name))
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--d3d9", default=r"C:\Windows\SysWOW64\d3d9.dll")
    ap.add_argument("--out", default="forwarders.h")
    ap.add_argument("--chain", default="d3d9_chain",
                    help="module name the forwarders point at (no extension)")
    ap.add_argument("--chain-copy", metavar="DIR",
                    help="also copy the source d3d9 into DIR as <chain>.dll")
    args = ap.parse_args()

    if not os.path.isfile(args.d3d9):
        sys.exit("source d3d9 not found: " + args.d3d9)

    names = exports(find_dumpbin(), args.d3d9)
    if not any(n == "Direct3DCreate9" for _, n in names):
        sys.exit("no Direct3DCreate9 export found; is %s really d3d9.dll?" % args.d3d9)

    # Forwarders by name only, as linker pragmas (a .def with "name=target @ord" fails to link;
    # the game imports d3d9 by name, so ordinals are not needed).
    lines = ["// generated by make_def.py from %s - do not edit by hand" % args.d3d9]
    for ordinal, name in names:
        lines.append('#pragma comment(linker, "/export:%s=%s.%s")' % (name, args.chain, name))
    with open(args.out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d forwarders)" % (args.out, len(names)))

    if args.chain_copy:
        os.makedirs(args.chain_copy, exist_ok=True)
        dest = os.path.join(args.chain_copy, args.chain + ".dll")
        shutil.copyfile(args.d3d9, dest)
        print("copied %s -> %s" % (args.d3d9, dest))


if __name__ == "__main__":
    main()
